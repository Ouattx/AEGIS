"""Shared connector plumbing: export payloads, HMAC signing, dry-run delivery, ledger records.

Every connector produces an :class:`ExportPayload` (the exact bytes that would leave the
process plus their SHA-256). Nothing is sent unless an :class:`ExportDelivery` is created
with ``dry_run=False``; the default is dry-run, which records what *would* be delivered.

Authentication reuses the MIRROR webhook scheme (HMAC-SHA256 over
``"<unix timestamp>." + body``, headers ``X-Aegis-Timestamp`` / ``X-Aegis-Delivery`` /
``X-Aegis-Signature: v1=<hex>``), so a receiver verifies exports and enforcement webhooks
with the same :func:`verify_export` / :func:`aegis.mirror.verify_webhook_signature` code.

Exports are notifications, never enforcement: a connector that could change an
enforcement point is a MIRROR adapter (see :mod:`aegis.connectors.ddos`) and only runs
through ``aegis.mirror.Executor`` after ``authorize``.
"""
from __future__ import annotations

import hashlib
import importlib.metadata
import time
from datetime import datetime, timezone
from typing import Any, Callable, Literal, Mapping
from urllib.parse import urlparse

import httpx
from pydantic import BaseModel, ConfigDict, Field

from aegis.contracts.models import new_id
from aegis.mirror.webhook import (
    DELIVERY_HEADER,
    EVENT_HEADER,
    MIN_SECRET_BYTES,
    SIGNATURE_HEADER,
    TIMESTAMP_HEADER,
    sign_webhook,
    verify_webhook_signature,
)
from aegis.provenance.ledger import Ledger

CONTENT_SHA_HEADER = "X-Aegis-Content-SHA256"
EXPORT_ENTRY = "connector_export"
PRODUCT_VENDOR = "AEGIS"
PRODUCT_NAME = "OMEGA SHIELD"

#: Heading carried by every proposal (FlowSpec text, DDoS-platform JSON).
PROPOSAL_NOTICE = ("PROPOSAL generated by AEGIS OMEGA SHIELD. NOT APPLIED. Requires review and an explicit "
                   "decision by a qualified network operator before any use. Verify syntax against your "
                   "platform and software release.")

_RETRY_STATUS = frozenset({408, 429})


def product_version() -> str:
    try:
        return importlib.metadata.version("aegis-omega")
    except importlib.metadata.PackageNotFoundError:  # running from a source tree without install
        return "0+source"


def utc(dt: datetime) -> datetime:
    if dt.tzinfo is None:
        raise ValueError("timestamps must be timezone-aware")
    return dt.astimezone(timezone.utc)


class ExportPayload(BaseModel):
    """The exact content a connector would deliver."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    connector: str                          # e.g. "siem.cef", "stix", "ddos.json", "flowspec.junos"
    tenant_id: str
    content_type: str
    body: str
    sha256: str
    records: int = Field(ge=0)
    generated_at: datetime
    proposal: bool = False                  # True => requires operator review, never auto-applied

    @classmethod
    def build(cls, connector: str, tenant_id: str, content_type: str, body: str, *, records: int,
              generated_at: datetime, proposal: bool = False) -> "ExportPayload":
        if not tenant_id or not tenant_id.strip():
            raise ValueError("tenant_id is required")
        return cls(connector=connector, tenant_id=tenant_id, content_type=content_type, body=body,
                   sha256=hashlib.sha256(body.encode("utf-8")).hexdigest(), records=records,
                   generated_at=utc(generated_at), proposal=proposal)

    @property
    def body_bytes(self) -> bytes:
        return self.body.encode("utf-8")


def _check_secret(secret: bytes) -> bytes:
    if not isinstance(secret, (bytes, bytearray)) or len(secret) < MIN_SECRET_BYTES:
        raise ValueError(f"HMAC secret must be at least {MIN_SECRET_BYTES} bytes")
    return bytes(secret)


def signature_headers(payload: ExportPayload, secret: bytes, *, timestamp: int,
                      delivery_id: str | None = None) -> dict[str, str]:
    """HTTP headers authenticating ``payload`` (same scheme as MIRROR webhooks)."""
    key = _check_secret(secret)
    return {
        "Content-Type": payload.content_type,
        TIMESTAMP_HEADER: str(int(timestamp)),
        DELIVERY_HEADER: delivery_id or new_id(),
        EVENT_HEADER: f"aegis.export.{payload.connector}",
        CONTENT_SHA_HEADER: payload.sha256,
        SIGNATURE_HEADER: sign_webhook(key, int(timestamp), payload.body_bytes),
    }


def verify_export(body: bytes, headers: Mapping[str, str], secret: bytes, *, now: float | None = None,
                  tolerance_s: int = 300) -> bool:
    """Receiver-side check: HMAC (constant time), timestamp freshness and content hash."""
    h = {k.lower(): v for k, v in headers.items()}
    sha = h.get(CONTENT_SHA_HEADER.lower())
    if sha is not None and sha != hashlib.sha256(body).hexdigest():
        return False
    return verify_webhook_signature(_check_secret(secret), h.get(TIMESTAMP_HEADER.lower(), ""), body,
                                    h.get(SIGNATURE_HEADER.lower(), ""), now=now, tolerance_s=tolerance_s)


class DeliveryResult(BaseModel):
    model_config = ConfigDict(extra="forbid")

    connector: str
    status: Literal["dry_run", "delivered", "failed"]
    dry_run: bool
    destination: str                        # scheme://host[:port]/path, never credentials
    delivery_id: str
    sha256: str
    records: int
    headers: dict[str, str] = Field(default_factory=dict)
    http_status: int | None = None
    error: str | None = None
    attempts: int = 0
    ledger_entry_hash: str | None = None


def _safe_destination(url: str) -> str:
    p = urlparse(url)
    host = p.hostname or ""
    port = f":{p.port}" if p.port else ""
    return f"{p.scheme}://{host}{port}{p.path}"


class ExportDelivery:
    """Delivers export payloads to one HTTPS endpoint; dry-run unless told otherwise.

    * ``dry_run=True`` (default): nothing leaves the process; the result carries the
      headers that would have been sent (signed when a secret is configured).
    * ``dry_run=False``: requires a secret (unsigned live deliveries are refused) and an
      ``https`` URL (``allow_insecure_http`` for lab receivers only). Retries transport
      errors, 408, 429 and 5xx with exponential backoff under one delivery id.

    With a ``ledger``, every delivery (dry-run included) is recorded as a
    ``connector_export`` entry carrying the content hash, never the content.
    """

    def __init__(self, url: str, *, secret: bytes | None = None, dry_run: bool = True,
                 ledger: Ledger | None = None, client: httpx.Client | None = None,
                 allow_insecure_http: bool = False, timeout_s: float = 10.0, max_attempts: int = 3,
                 backoff_s: float = 0.5, sleep: Callable[[float], None] = time.sleep,
                 clock: Callable[[], float] = time.time):
        parsed = urlparse(url)
        if parsed.scheme not in ("https", "http") or not parsed.netloc:
            raise ValueError("delivery url must be an absolute http(s) URL")
        if parsed.username or parsed.password:
            raise ValueError("credentials in the URL are not allowed; use the HMAC secret")
        if parsed.scheme == "http" and not allow_insecure_http:
            raise ValueError("delivery url must use https (set allow_insecure_http for lab use)")
        if max_attempts < 1:
            raise ValueError("max_attempts must be >= 1")
        self._secret = _check_secret(secret) if secret is not None else None
        if not dry_run and self._secret is None:
            raise ValueError("live delivery requires an HMAC secret (unsigned exports are refused)")
        self.url = url
        self.dry_run = dry_run
        self.ledger = ledger
        self._client = client
        self._timeout = timeout_s
        self.max_attempts = max_attempts
        self.backoff_s = backoff_s
        self._sleep = sleep
        self._clock = clock

    def __repr__(self) -> str:  # never leak the secret
        return f"ExportDelivery(url={_safe_destination(self.url)!r}, dry_run={self.dry_run})"

    def deliver(self, payload: ExportPayload, *, actor: str) -> DeliveryResult:
        if not actor or not actor.strip():
            raise ValueError("actor is required (who triggered the export)")
        delivery_id = new_id()
        dest = _safe_destination(self.url)
        base = dict(connector=payload.connector, destination=dest, delivery_id=delivery_id,
                    sha256=payload.sha256, records=payload.records, dry_run=self.dry_run)
        if self.dry_run:
            headers = (signature_headers(payload, self._secret, timestamp=int(self._clock()),
                                         delivery_id=delivery_id) if self._secret is not None
                       else {"Content-Type": payload.content_type, CONTENT_SHA_HEADER: payload.sha256})
            res = DeliveryResult(status="dry_run", headers=headers, **base)
            return self._record(payload, res, actor)
        assert self._secret is not None  # guaranteed by __init__
        if self._client is not None:
            return self._record(payload, self._send(self._client, payload, delivery_id, base), actor)
        with httpx.Client(timeout=self._timeout) as client:
            return self._record(payload, self._send(client, payload, delivery_id, base), actor)

    def _send(self, client: httpx.Client, payload: ExportPayload, delivery_id: str,
              base: dict[str, Any]) -> DeliveryResult:
        assert self._secret is not None
        last_error = "no attempt made"
        status: int | None = None
        for attempt in range(1, self.max_attempts + 1):
            headers = signature_headers(payload, self._secret, timestamp=int(self._clock()),
                                        delivery_id=delivery_id)
            try:
                resp = client.post(self.url, content=payload.body_bytes, headers=headers, timeout=self._timeout)
            except httpx.HTTPError as exc:
                last_error = f"transport error: {type(exc).__name__}"
                status = None
            else:
                status = resp.status_code
                if 200 <= status < 300:
                    return DeliveryResult(status="delivered", http_status=status, attempts=attempt, **base)
                last_error = f"HTTP {status}"
                if status < 500 and status not in _RETRY_STATUS:
                    return DeliveryResult(status="failed", http_status=status, error=last_error,
                                          attempts=attempt, **base)
            if attempt < self.max_attempts:
                self._sleep(self.backoff_s * (2 ** (attempt - 1)))
        return DeliveryResult(status="failed", http_status=status, error=last_error, attempts=self.max_attempts,
                              **base)

    def _record(self, payload: ExportPayload, res: DeliveryResult, actor: str) -> DeliveryResult:
        if self.ledger is None:
            return res
        entry = record_export(self.ledger, payload, actor=actor, status=res.status, destination=res.destination,
                              delivery_id=res.delivery_id, extra={"http_status": res.http_status,
                                                                  "attempts": res.attempts, "error": res.error})
        return res.model_copy(update={"ledger_entry_hash": entry})


def record_export(ledger: Ledger, payload: ExportPayload, *, actor: str, status: str,
                  destination: str | None = None, delivery_id: str | None = None,
                  extra: dict[str, Any] | None = None) -> str:
    """Write a ``connector_export`` ledger entry (content hash only); returns the entry hash."""
    entry = ledger.append(payload.tenant_id, EXPORT_ENTRY, delivery_id or payload.sha256[:32], {
        "connector": payload.connector, "status": status, "actor": actor, "sha256": payload.sha256,
        "records": payload.records, "content_type": payload.content_type, "proposal": payload.proposal,
        "generated_at": payload.generated_at.isoformat(), "destination": destination,
        "delivery_id": delivery_id, **(extra or {})})
    return entry.entry_hash


